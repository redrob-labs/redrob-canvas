std::wstring StatusText(Stage s) {
  if (!g_statusOverride.empty()) return g_statusOverride;
  switch (s) {
    case Stage::Preparing:  return L"Preparing\u2026";
    case Stage::Installing: return L"Installing\u2026";
    case Stage::Opening:    return L"Opening Redrob Canvas\u2026";
    case Stage::Error:      return L"Something went wrong";
    case Stage::Confirm:    return L"Uninstall Redrob Canvas?";
    case Stage::Removing:   return L"Removing Redrob Canvas\u2026";
    case Stage::Removed:    return L"Redrob Canvas has been removed";
    case Stage::Welcome:    return L"Install Redrob Canvas";
    case Stage::InstallingCode: return L"Installing Redrob Code\u2026";
    case Stage::CodeFailed: return L"Redrob Canvas is installed";
  }
  return L"";
}

// What the error screen says for a worker's result. Retry is on the screen, so each one says what to do.
std::wstring ResultSentence(DWORD code, bool uninstall) {
  if (code == kResultAppRunning)
    return uninstall ? L"Redrob Canvas is open. Save your work, close it, then press Retry."
                     : L"Redrob Canvas is open. Save your work, close it, then press Retry to update it.";
  if (code == kResultUnpackFailed) return L"The app files could not be unpacked. Please try again.";
  if (code == kResultNoExe) return L"This setup file is damaged. Please download it again.";
  if (code == ERROR_DISK_FULL || code == ERROR_HANDLE_DISK_FULL)
    return L"There is not enough free disk space. Free some space, then press Retry.";
  if (code == ERROR_ACCESS_DENIED || code == ERROR_SHARING_VIOLATION)
    return L"A file is in use. Close Redrob Canvas and anything opened from its folder, then press Retry.";
  return (uninstall ? L"Redrob Canvas could not be removed (code " : L"Setup did not complete (code ") +
         std::to_wstring(code) + L"). Please try again.";
}

