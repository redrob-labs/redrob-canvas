// redrob_canvas_setup -- the branded Windows setup and uninstaller for Redrob Canvas.
//
// Adapted from the Redrob Browser setup window (redrob-labs/redrob-browser, installer/windows/), which is
// our own code. The window, the design-system rules and the Redrob Code opt-in are the same. What differs
// is the install itself: the browser hands that to Chromium's mini_installer, and Canvas has no such thing,
// so this app does it.
//
// What it is: a native Win32 app, no dependencies beyond the Windows SDK. It renders a small borderless,
// rounded, DWM-shadowed window with the Redrob Canvas lockup, a status line and a progress bar.
//
// Design system (redrob-design-system):
//   * Ground "deep" (20-color.md): field is Redrob Black #0A0B0C. type is gray-1 / gray-5; the call to
//     action is a white pill with black type.
//   * "Blue acts" (20-color.md): the progress fill is action-primary, Redrob Blue #2B52FF.
//   * Product color is "where you are, never what you read": Canvas's colour appears only in the window icon; the lockup is the Redrob mark and name.
//   * Foot light is `wash-edge` from the brand gradient (blue-6 -> accent-teal-3), pre-rendered into
//     res/background.png from res/background.html.
//   * Type is Pretendard (30-typography.md), embedded in-memory when available, else Segoe UI Variable.
//   * Motion: every transition under a third of a second (40-surfaces-and-motion.md).
//
// Install (per user, no administrator rights):
//   1. The payload is the release's own signed zip, embedded as RCDATA. It is written to %TEMP% and
//      unpacked with Windows' own tar.exe (bsdtar, in System32 since Windows 10 1803, reads zip) into
//      %LOCALAPPDATA%\Programs\Redrob Canvas.new.
//   2. The old install, if any, is renamed aside and the new one renamed into place, so a failed update
//      never leaves half of two versions. A running Redrob Canvas keeps its files locked; the setup asks
//      the person to close it rather than closing it for them, because it may hold unsaved work.
//   3. The uninstaller (this same app built without a payload) is written into the install folder;
//      Start-menu and desktop shortcuts are made; the Settings > Apps entry is written under HKCU.
//   4. Redrob Canvas is opened.
// The steps report no progress of their own, so the bar is a time-based eased ramp capped at ~90% until
// they finish.
//
// Uninstall (Settings > Apps, or the uninstaller directly): confirm, with "Also delete settings and the
// AI engine" off by default; remove the shortcuts, the Settings > Apps entry and the install folder. The
// running uninstaller cannot delete itself, so a hidden PowerShell removes it and the folder once it exits.
//
// Redrob Code (opt-in): the first screen asks before anything is installed, with "Also install Redrob Code"
// OFF by default. Canvas's Agent panel drives it. When chosen it goes in first: the latest release's
// redrob-code-x64-setup.exe is downloaded from GitHub, checked against that release's SHA256SUMS, and run
// silently per-user. A Redrob Code failure never fails the Canvas install; the last screen says why.
//
// Flags:
//   --with-redrob-code   start with "Also install Redrob Code" ticked (still shown, still a choice).
//   --demo               run the whole install sequence on a timer with NO payload (and no download).
//   --demo-error         show the error state immediately.
//   --demo-code-error    --demo, ending on the "Redrob Code was not installed" screen.
//   --uninstall          remove Redrob Canvas (what Settings > Apps runs).
//   --demo-uninstall     the uninstall sequence on a timer, removing nothing.
//   (no flag)            install the embedded payload for real.

